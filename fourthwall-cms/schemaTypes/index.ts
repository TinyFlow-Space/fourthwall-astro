import { contentTypes, managedMedia, seo } from "./content";
import { product, productCategory } from "./product";
import { richContent } from "./richContent";
import { defineArrayMember, defineField, defineType } from "sanity";
const slug = defineField({
  name: "slug",
  type: "slug",
  options: { source: "title", maxLength: 96 },
  validation: (rule) =>
    rule
      .required()
      .custom((value) =>
        !value?.current || /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value.current)
          ? true
          : "Use lowercase letters, numbers and hyphens.",
      ),
});
const imageFields = [
  defineField({
    name: "alt",
    type: "string",
    title: "Alternative text",
    validation: (rule) => rule.required(),
  }),
  defineField({ name: "caption", type: "string" }),
];
// Video metadata fields are required only once a YouTube ID has been entered.
const requiredWithVideo = (value: unknown, context: { parent?: unknown }) =>
  !(context.parent as { id?: string } | undefined)?.id?.trim() ||
  (typeof value === "string" ? value.trim() : value)
    ? true
    : "Required when a YouTube video ID is set.";
const taxonomy =(name: "category" | "tag") =>
  defineType({
    name,
    title: name === "category" ? "Category" : "Tag",
    type: "document",
    fields: [
      defineField({
        name: "title",
        type: "string",
        validation: (rule) => rule.required(),
      }),
      slug,
    ],
  });
export const schemaTypes = [
  ...contentTypes, managedMedia, seo, product, productCategory,
  taxonomy("category"),
  taxonomy("tag"),
  defineType({
    name: "author",
    type: "document",
    fields: [
      defineField({
        name: "name",
        type: "string",
        validation: (rule) => rule.required(),
      }),
      defineField({ name: "role", type: "string" }),
      defineField({ name: "bio", type: "text", rows: 4 }),
      defineField({
        name: "website",
        type: "url",
        validation: (rule) => rule.uri({ scheme: ["https", "http"] }),
      }),
      defineField({
        name: "image",
        type: "image",
        options: { hotspot: true },
        fields: imageFields,
      }),
    ],
  }),
  defineType({
    name: "post",
    type: "document",
    fields: [
      defineField({
        name: "title",
        type: "string",
        validation: (rule) => rule.required().max(150),
      }),
      slug,
      defineField({name: "seo", type: "seo"}),
      defineField({name: "audioUrl", title: "Audio URL", type: "url", description: "Optional pre-recorded narration. No audio is generated by the website.", validation: r => r.uri({scheme:["https"]})}),
      defineField({name: "audioDuration", title: "Audio duration (seconds)", type: "number", validation: r => r.min(0)}),
      defineField({name: "relatedPosts", title: "Related blogs (optional override)", type: "array", of:[{type:"reference",to:[{type:"post"}]}], validation:r=>r.unique().max(3)}),
      defineField({
        name: "excerpt",
        type: "text",
        rows: 3,
        validation: (rule) => rule.required().max(320),
      }),
      defineField({
        name: "mainImage",
        title: "Featured image",
        type: "image",
        options: { hotspot: true },
        fields: imageFields,
        validation: (rule) => rule.required().assetRequired(),
      }),
      defineField({
        name: "video",
        title: "Video Settings",
        description:
          "Required fields for showing YouTube video instead of featured image on blog details page",
        type: "object",
        options: { collapsible: true, collapsed: false },
        fields: [
          defineField({
            name: "id",
            title: "YouTube Video ID",
            type: "string",
            description:
              "Only the ID, e.g. [ k_ABBzuH3ww ] from (https://www.youtube.com/watch?v=k_ABBzuH3ww). When set, the video replaces the main image on the post details page.",
            validation: (rule) =>
              rule.custom((value) =>
                !value || /^[\w-]{11}$/.test(value.trim())
                  ? true
                  : "Enter only the 11-character video ID, e.g. k_ABBzuH3ww.",
              ),
          }),
          defineField({
            name: "title",
            title: "YouTube Video Title",
            type: "string",
            description: "Title of the YouTube video. Required if a video is set.",
            validation: (rule) => rule.custom(requiredWithVideo).max(150),
          }),
          defineField({
            name: "description",
            title: "YouTube Video Description",
            type: "string",
            description: "1–2 sentences about the video. Required if a video is set.",
            validation: (rule) => rule.custom(requiredWithVideo).max(320),
          }),
          defineField({
            name: "uploadDate",
            title: "YouTube Video Upload Date",
            type: "datetime",
            description:
              "The date the video was published on YouTube (not the blog date). Required if a video is set.",
            validation: (rule) => rule.custom(requiredWithVideo),
          }),
          defineField({
            name: "duration",
            title: "YouTube Video Duration",
            type: "string",
            description:
              "Video length as shown on YouTube, e.g. 4:13 or 1:02:45 . Required if a video is set.",
            validation: (rule) =>
              rule.custom((value, context) => {
                const required = requiredWithVideo(value, context);
                if (required !== true) return required;
                return !value || /^(?:\d+:)?[0-5]?\d:[0-5]\d$/.test(value.trim())
                  ? true
                  : "Use m:ss or h:mm:ss, e.g. 4:13 or 1:02:45.";
              }),
          }),
          defineField({
            name: "thumbnail",
            title: "YouTube Video Thumbnail",
            type: "image",
            description:
              "YouTube video thumbnail. Aspect ratio must be (16:9). Required if a video is set.",
            options: { hotspot: true },
            fields: [
              defineField({
                name: "alt",
                type: "string",
                title: "Alternative text",
              }),
            ],
            validation: (rule) => [
              rule.custom((value: { asset?: { _ref?: string } } | undefined, context) =>
                requiredWithVideo(value?.asset?._ref, context),
              ),
              // Asset IDs embed dimensions: image-<hash>-<w>x<h>-<ext>.
              rule
                .custom((value: { asset?: { _ref?: string } } | undefined) => {
                  const size = value?.asset?._ref?.match(/-(\d+)x(\d+)-/);
                  if (!size) return true;
                  const ratio = Number(size[1]) / Number(size[2]);
                  return Math.abs(ratio - 16 / 9) < 0.02
                    ? true
                    : "Image is not 16:9; it will be cropped to 16:9 around the hotspot.";
                })
                .warning(),
            ],
          }),
        ],
      }),
      defineField({
        name: "author",
        type: "reference",
        to: [{ type: "author" }],
        validation: (rule) => rule.required(),
      }),
      defineField({
        name: "publishedAt",
        type: "datetime",
        initialValue: () => new Date().toISOString(),
        validation: (rule) => rule.required(),
      }),
      defineField({
        name: "updatedAt",
        title: "Updated at",
        type: "datetime",
        description:
          "Set automatically each time a published post is republished. When later than the published date, it is shown on blog cards and used for sorting. Change it by hand to override.",
        validation: (rule) =>
          rule.custom((value, context) => {
            const publishedAt = (context.document as { publishedAt?: string })
              ?.publishedAt;
            return !value ||
              !publishedAt ||
              new Date(value) >= new Date(publishedAt)
              ? true
              : "Updated date is earlier than the published date and will be ignored.";
          }).warning(),
      }),
      defineField({ name: "featured", type: "boolean", initialValue: false }),
      defineField({
        name: "categories",
        type: "array",
        of: [
          defineArrayMember({ type: "reference", to: [{ type: "category" }] }),
        ],
        validation: (rule) => rule.unique(),
      }),
      defineField({
        name: "tags",
        type: "array",
        of: [defineArrayMember({ type: "reference", to: [{ type: "tag" }] })],
        validation: (rule) => rule.unique(),
      }),
      defineField({
        name: "enableAudio",
        title: "Enable audio",
        type: "boolean",
        initialValue: false,
        description:
          "Shows narration only when an Audio URL is configured.",
      }),
      defineField({
        name: "summary",
        title: "TL;DR summary",
        type: "text",
        rows: 3,
      }),
      defineField({
        name: "body",
        type: "array",
        validation: (rule) => rule.required().min(1),
        of: [
          ...richContent,
          defineArrayMember({
            type: "block",
            styles: [
              { title: "Normal", value: "normal" },
              { title: "Heading 2", value: "h2" },
              { title: "Heading 3", value: "h3" },
              { title: "Quote", value: "blockquote" },
            ],
            marks: {
              decorators: [
                { title: "Strong", value: "strong" },
                { title: "Emphasis", value: "em" },
                { title: "Code", value: "code" },
              ],
              annotations: [
                {
                  name: "link",
                  type: "object",
                  fields: [
                    {
                      name: "href",
                      type: "url",
                      validation: (rule) =>
                        rule.required().uri({
                          allowRelative: true,
                          scheme: ["https", "http", "mailto"],
                        }),
                    },
                  ],
                },
              ],
            },
          }),
          defineArrayMember({
            type: "image",
            options: { hotspot: true },
            fields: imageFields,
          }),
        ],
      }),
      defineField({
        name: "faqs",
        title: "FAQs",
        type: "array",
        of: [
          defineArrayMember({
            name: "faq",
            type: "object",
            fields: [
              defineField({
                name: "question",
                type: "string",
                validation: (rule) => rule.required(),
              }),
              defineField({
                name: "answer",
                type: "text",
                validation: (rule) => rule.required(),
              }),
            ],
          }),
        ],
      }),
    ],
    preview: {
      select: { title: "title", subtitle: "author.name", media: "mainImage" },
    },
    orderings: [
      {
        title: "Publication date",
        name: "publishedAtDesc",
        by: [{ field: "publishedAt", direction: "desc" }],
      },
      {
        title: "Last updated",
        name: "updatedAtDesc",
        by: [
          { field: "updatedAt", direction: "desc" },
          { field: "publishedAt", direction: "desc" },
        ],
      },
    ],
  }),
];
